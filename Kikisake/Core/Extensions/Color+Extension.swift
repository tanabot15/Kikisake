import SwiftUI

extension Color {
    /// アプリ共通のアクセントカラー
    public static let kikisakePrimary = Color.accentColor
    
    /// グループ化されたリスト等の背景色
    public static let kikisakeBackground = Color(.systemGroupedBackground)
    
    /// カードやセルの背景色
    public static let kikisakeCardBackground = Color(.secondarySystemGroupedBackground)
}
